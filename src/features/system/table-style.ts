/**
 * 시스템(운영자) 표가 함께 쓰는 머리 줄 규격.
 *
 * ⚠️ **띠를 `--secondary`로 깔 수 없다.** 라이트에서 `--secondary`(`#fafaf9`)가
 *    카드 흰색(`#ffffff`)과 거의 같아서, `/50`까지 씌우면 대비가 **1.02:1**이다 —
 *    머리 줄이 있는지도 안 보였다(표 5개가 전부 그랬다). `--muted`·`--accent`도
 *    같은 값이라 토큰을 바꿔 봐야 소용이 없다.
 * ⚠️ 그래서 **먹색을 옅게 깐다.** 한 클래스로 두 테마가 다 된다 — 라이트에선 흰 바탕이
 *    살짝 어두워지고, 다크에선 `--foreground`가 밝은 색이라 카드보다 밝아진다.
 * ⚠️ **6%다.** 행 hover가 4%(`hover:bg-foreground/[0.04]`)라, 머리가 그보다 옅으면
 *    마우스를 얹은 행이 머리보다 진해져 위아래가 뒤집혀 보인다.
 * ⚠️ 아래 보더를 같이 둔다. 띠만으로는 어느 테마에서든 경계가 흐리다.
 * ⚠️ **hover에도 같은 띠를 유지한다.** `TableRow`가 기본으로 `hover:bg-muted/50`을 걸어서
 *    그걸 지워야 하는데, `hover:bg-transparent`로 지웠더니 **마우스를 얹는 순간 띠가 통째로
 *    사라졌다.** 머리 줄은 누르는 자리가 아니라 반응할 이유가 없다 — 같은 값을 다시 줘서
 *    아무 일도 일어나지 않게 한다. (띠가 안 보이던 때는 이 버그도 안 보였다.)
 */
export const TABLE_HEAD_ROW_CLASS =
  "bg-foreground/[0.06] border-border border-b hover:bg-foreground/[0.06]";

/**
 * 표 머리 **셀** 규격 — 높이는 여기 있다.
 *
 * ⚠️ **높이를 `<tr>`에 걸면 안 먹는다.** `TableHead`가 `<th>`마다 `h-10`을 얹고
 *    (`components/ui/table.tsx`), 행 높이는 셀이 정한다 — 표 다섯 개가 저마다
 *    `h-9`·`h-[34px]`를 행에 걸어 두고 실제로는 전부 40px로 그려지고 있었다.
 *    눈에 안 보이는 채로 한 칸씩 두꺼웠다.
 * ⚠️ 그래서 값을 **한 자리로 모은다.** 다섯 표가 같은 화면군에 있어 머리 높이가 갈리면
 *    사이드바로 옮겨 다닐 때 표가 한 칸씩 뛴다.
 */
export const TABLE_HEAD_CELL_CLASS = "h-9 text-xs";

/** 위 클래스의 픽셀값 — 빈 목록 자리를 잡을 때 쓴다(`h-9` = 36px). */
export const TABLE_HEAD_HEIGHT_PX = 36;

/**
 * 열 정렬 규칙 — 시스템 표 다섯 개가 같이 지킨다.
 *
 * ⚠️ **머리글은 값의 가운데에 온다.** 첫 열(그 줄의 주인공)만 왼쪽이고, 나머지 열은
 *    머리글·값 **둘 다 가운데**다. 한때 양끝(왼쪽/오른쪽)을 맞춰 봤는데, 머리글이 값의
 *    한쪽 끝에 붙어 서서 어느 값을 가리키는지 눈으로 안 잡혔다.
 * ⚠️ 숫자는 `tabular-nums`로 자릿수 폭을 고정한다 — 가운데 정렬에서도 자리가 덜 흔들린다.
 * ⚠️ 버튼·뱃지가 든 열도 가운데다. 상자를 한쪽 끝에 맞추면 상자 안쪽 여백만큼
 *    **글자끼리** 어긋난다(실측 9px) — 가운데로 두면 상자 중심과 글자 중심이 같아 그 문제가
 *    아예 없다.
 */
